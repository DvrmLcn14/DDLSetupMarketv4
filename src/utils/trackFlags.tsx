export function getTrackFlagImg(trackId?: string, countryOrTrackName?: string): string {
  if (trackId && TRACK_FLAG_IMAGES[trackId.toLowerCase()]) {
    return TRACK_FLAG_IMAGES[trackId.toLowerCase()];
  }

  if (countryOrTrackName) {
    const lower = countryOrTrackName.toLowerCase();
    for (const [key, flagImg] of Object.entries(COUNTRY_NAME_FLAG_IMAGES)) {
      if (lower.includes(key)) {
        return flagImg;
      }
    }
  }

  return '/flags/gb.png';
}

export function getTrackFlagEmoji(trackId?: string, countryOrTrackName?: string): string {
  if (trackId && TRACK_FLAGS[trackId.toLowerCase()]) {
    return TRACK_FLAGS[trackId.toLowerCase()];
  }

  if (countryOrTrackName) {
    const lower = countryOrTrackName.toLowerCase();
    for (const [key, flag] of Object.entries(COUNTRY_NAME_FLAGS)) {
      if (lower.includes(key)) {
        return flag;
      }
    }
  }

  return '🏁';
}

export const TrackFlagIcon: React.FC<{
  trackId?: string;
  countryOrTrackName?: string;
  className?: string;
  size?: 'xs' | 'sm' | 'md' | 'lg' | 'xl';
}> = ({ trackId, countryOrTrackName, className = '', size = 'md' }) => {
  const flagSrc = getTrackFlagImg(trackId, countryOrTrackName);
  
  const sizeMap: Record<'xs' | 'sm' | 'md' | 'lg' | 'xl', string> = {
    xs: 'w-3.5 h-2 rounded-sm',
    sm: 'w-4 h-2.5 rounded-sm',
    md: 'w-5 h-3 rounded-sm',
    lg: 'w-6 h-4 rounded-sm',
    xl: 'w-8 h-5.5 rounded',
  };

  const sizeClasses = sizeMap[size] || sizeMap.md;

  return (
    <img
      src={flagSrc}
      alt={countryOrTrackName || trackId || 'Track flag'}
      className={`${sizeClasses} object-cover shadow-sm border border-slate-700/60 inline-block align-middle flex-shrink-0 ${className}`}
      referrerPolicy="no-referrer"
    />
  );
};

